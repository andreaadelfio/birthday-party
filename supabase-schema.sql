create trigger trigger_sync_guest_group_members_count
after insert or update or delete
on public.event_registrations
for each row
execute function public.sync_guest_group_members_count();

drop function if exists public.register_guest(text,text,text,integer,text,text,text,boolean);
create or replace function public.register_guest(
  p_name text,
  p_surname text,
  p_username text,
  p_guests_count integer default 1,
  p_notes text default null,
  p_group_slug text default 'default',
  p_new_group_name text default null,
  p_will_be_there boolean default false,
  p_stay_dates text default null,
  p_host_dates text default null,
  p_hosted_by_friend boolean default false
)
returns table (
  registration_id uuid,
  registration_username text,
  group_slug text,
  group_name text,
  saved_mode text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_group_id uuid;
  v_group_slug text;
  v_group_name text;
  v_username text;
  v_full_name text;
  v_registration_id uuid;
  v_registration_exists boolean;
begin
  if nullif(trim(coalesce(p_name, '')), '') is null then
    raise exception 'Name is required';
  end if;

  if nullif(trim(coalesce(p_surname, '')), '') is null then
    raise exception 'Surname is required';
  end if;

  if nullif(trim(coalesce(p_username, '')), '') is null then
    raise exception 'Username is required';
  end if;

  if coalesce(p_guests_count, 0) < 1 then
    raise exception 'Guests count must be at least 1';
  end if;

  v_username := lower(trim(p_username));
  v_full_name := trim(concat_ws(' ', trim(p_name), trim(p_surname)));

  if nullif(trim(coalesce(p_new_group_name, '')), '') is not null then
    v_group_name := trim(p_new_group_name);
    v_group_slug := trim(both '-' from regexp_replace(lower(v_group_name), '[^a-z0-9]+', '-', 'g'));

    if v_group_slug = '' then
      raise exception 'New group name is not valid';
    end if;

    insert into public.guest_groups (name, slug, is_default, sort_order)
    values (v_group_name, v_group_slug, false, 999)
    on conflict (slug) do nothing
    returning id, slug, name
    into v_group_id, v_group_slug, v_group_name;

    if v_group_id is null then
      select id, slug, name
      into v_group_id, v_group_slug, v_group_name
      from public.guest_groups
      where slug = v_group_slug
      limit 1;
    end if;
  else
    select id, slug, name
    into v_group_id, v_group_slug, v_group_name
    from public.guest_groups
    where slug = coalesce(nullif(trim(p_group_slug), ''), 'default')
    limit 1;

    if v_group_id is null then
      select id, slug, name
      into v_group_id, v_group_slug, v_group_name
      from public.guest_groups
      where slug = 'default'
      limit 1;
    end if;
  end if;

  if v_group_id is null then
    raise exception 'No valid group found. Seed the default groups first.';
  end if;

  select exists (
    select 1
    from public.event_registrations as er
    where er.username = v_username
  ) into v_registration_exists;

  insert into public.event_registrations (
    name,
    surname,
    full_name,
    username,
    guests_count,
    notes,
    group_id,
    will_be_there,
    stay_dates,
    host_dates,
    hosted_by_friend
  )
  values (
    trim(p_name),
    trim(p_surname),
    v_full_name,
    v_username,
    p_guests_count,
    nullif(trim(coalesce(p_notes, '')), ''),
    v_group_id,
    p_will_be_there,
    nullif(trim(coalesce(p_stay_dates, '')), ''),
    nullif(trim(coalesce(p_host_dates, '')), ''),
    p_hosted_by_friend
  )
  on conflict (username) do update
  set
    name = excluded.name,
    surname = excluded.surname,
    full_name = excluded.full_name,
    guests_count = excluded.guests_count,
    notes = excluded.notes,
    group_id = excluded.group_id,
    will_be_there = excluded.will_be_there,
    stay_dates = excluded.stay_dates,
    host_dates = excluded.host_dates,
    hosted_by_friend = excluded.hosted_by_friend,
    updated_at = timezone('utc', now())
  returning id
  into v_registration_id;

  return query
  select
    v_registration_id,
    v_username,
    v_group_slug,
    v_group_name,
    case when v_registration_exists then 'updated' else 'created' end;
end;
$$;

