create or replace function update_lista_invitati_on_registration()
returns trigger as $$
declare
  v_group_slug text;
begin
  update public.lista_invitati
  set
    has_registered = true,
    number_of_guests = new.guests_count,
    will_be_there = new.will_be_there,
    registration_id = new.id,
    name = coalesce(nullif(new.name, ''), name),
    surname = coalesce(nullif(new.surname, ''), surname),
    full_name = coalesce(nullif(new.full_name, ''), full_name)
  where full_name = new.full_name;

  if not found then
    select slug
    into v_group_slug
    from public.guest_groups
    where id = new.group_id
    limit 1;

    insert into public.lista_invitati (
      name,
      surname,
      full_name,
      has_registered,
      number_of_guests,
      is_invited,
      group_slug,
      will_be_there,
      registration_id
    )
    values (
      new.name,
      new.surname,
      new.full_name,
      true,
      new.guests_count,
      false,
      v_group_slug,
      new.will_be_there,
      new.id
    );
  end if;

  return new;
end;
$$ language plpgsql;

drop trigger if exists trigger_update_lista_invitati on public.event_registrations;
create trigger trigger_update_lista_invitati
  after insert or update on public.event_registrations
  for each row execute function update_lista_invitati_on_registration();

create or replace function public.sync_guest_group_members_count()
returns trigger
language plpgsql
as $$
begin
  if tg_op in ('UPDATE', 'DELETE') then
    update public.guest_groups gg
    set members_count = (
      select coalesce(sum(er.guests_count), 0)
      from public.event_registrations er
      where er.group_id = old.group_id
      and er.will_be_there = true
    )
    where gg.id = old.group_id;
  end if;

  if tg_op in ('INSERT', 'UPDATE') then
    update public.guest_groups gg
    set members_count = (
      select coalesce(sum(er.guests_count), 0)
      from public.event_registrations er
      where er.group_id = new.group_id
      and er.will_be_there = true
    )
    where gg.id = new.group_id;
  end if;

  return null;
end;
$$;

drop trigger if exists trigger_sync_guest_group_members_count
